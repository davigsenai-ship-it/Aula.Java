package lista_de_exercicios;

public class Exercicio6 {
    public static void main(String[] args) {
        int variavel_a = 17;
        int variavel_b = 18;

        System.out.println("17 > 18 ="+ (variavel_a > variavel_b));
        System.out.println("17 < 18 ="+ (variavel_a < variavel_b));
        System.out.println("17 >= 18 ="+ (variavel_a >= variavel_b));
        System.out.println("17 <= 18 ="+ (variavel_a <= variavel_b));
        System.out.println("17 == 18 ="+ (variavel_a == variavel_b));
        System.out.println("17 != 18 ="+ (variavel_a != variavel_b));
    }
}